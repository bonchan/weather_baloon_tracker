import { useSyncExternalStore } from 'react'

/** One decoded position report. */
export type SondeFix = {
  serial: string
  /** The sonde's own frame counter. */
  frame: number
  /** GPS time of the fix, ms since epoch. */
  time: number
  lat: number
  lon: number
  /** Meters above the WGS84 ellipsoid. */
  alt: number
  /** Vertical speed, m/s, positive up. */
  climb?: number
  /** Ground speed, m/s. */
  speed?: number
  /** Course over ground, degrees true. */
  heading?: number
  temperature?: number
  humidity?: number
  /** Measured, hPa; only sondes with a pressure sensor (RS41-SGP) send it. */
  pressure?: number
  /** Date.now() when the frame was decoded. */
  receivedAt: number
}

export type SondeTrack = {
  serial: string
  fixes: SondeFix[]
  /** Generated by the demo flight, not received. */
  demo: boolean
}

export type SondeState = {
  tracks: Record<string, SondeTrack>
  /** Serial of the sonde heard most recently. */
  active: string | null
}

/**
 * Received sonde tracks. The decoder feeds addFix(); the map and info panels read the
 * state. Persistence to IndexedDB comes later.
 */
class SondeStore {
  private state: SondeState = { tracks: {}, active: null }
  private listeners = new Set<() => void>()

  subscribe = (listener: () => void) => {
    this.listeners.add(listener)
    return () => {
      this.listeners.delete(listener)
    }
  }

  getState = () => this.state

  addFix(fix: SondeFix, demo = false) {
    const prev = this.state.tracks[fix.serial]
    const last = prev?.fixes[prev.fixes.length - 1]
    if (last && last.frame === fix.frame) return
    const track: SondeTrack = { serial: fix.serial, demo, fixes: prev ? [...prev.fixes, fix] : [fix] }
    this.set({ tracks: { ...this.state.tracks, [fix.serial]: track }, active: fix.serial })
  }

  clearTracks(onlyDemo = false) {
    const tracks = onlyDemo
      ? Object.fromEntries(Object.entries(this.state.tracks).filter(([, t]) => !t.demo))
      : {}
    const active = this.state.active && tracks[this.state.active] ? this.state.active : null
    this.set({ tracks, active })
  }

  private set(patch: Partial<SondeState>) {
    this.state = { ...this.state, ...patch }
    for (const l of this.listeners) l()
  }
}

export const sondes = new SondeStore()

export function useSondes(): SondeState {
  return useSyncExternalStore(sondes.subscribe, sondes.getState)
}
